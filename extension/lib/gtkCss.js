// GTK4 (libadwaita CSS variables) and GTK3 (adw-gtk3 named colors) stylesheets.
import GLib from 'gi://GLib';

import {resolveVariant} from './palette.js';

export const GENERATED_HEADER = '/* Generated by Paletka — do not edit. */';

export function hasGeneratedHeader(text) {
    return typeof text === 'string' && text.startsWith(GENERATED_HEADER);
}

// A user gtk.css that pins surface colors with the legacy @define-color syntax
// (e.g. left by Gradience). Yaru's libadwaita still honors some of them, which
// leaves surfaces light while the text turns light in dark mode.
const LEGACY_SURFACE_RE = /^\s*@define-color\s+(?:window|view|headerbar|card|popover|sidebar|dialog)_(?:bg|fg)_color\b/m;

export function hasLegacyColorDefinitions(text) {
    return typeof text === 'string' && !hasGeneratedHeader(text) && LEGACY_SURFACE_RE.test(text);
}

// Palette keys that libadwaita exposes as --<key>-color.
const ADW_KEYS = [
    'window_bg', 'window_fg', 'view_bg', 'view_fg',
    'headerbar_bg', 'headerbar_fg', 'headerbar_border', 'headerbar_shade',
    'sidebar_bg', 'sidebar_fg', 'card_bg', 'card_fg',
    'popover_bg', 'popover_fg', 'dialog_bg', 'dialog_fg',
    'accent', 'accent_bg', 'accent_fg',
    'destructive_bg', 'destructive_fg', 'success_bg', 'success_fg',
    'warning_bg', 'warning_fg', 'error_bg', 'error_fg',
    'border', 'shade',
];

const adwVar = key => `--${key.replaceAll('_', '-')}-color`;

function rootBlock(palette, indent) {
    const lines = ADW_KEYS.map(k => `${indent}  ${adwVar(k)}: ${palette[k]};`);
    return `${indent}:root {\n${lines.join('\n')}\n${indent}}`;
}

export function gtk4Css(family) {
    const light = resolveVariant(family.light, false);
    const dark = resolveVariant(family.dark, true);
    return `${GENERATED_HEADER}
/* Theme: ${family.name} */
${rootBlock(light, '')}

@media (prefers-color-scheme: dark) {
${rootBlock(dark, '  ')}
}
`;
}

// adw-gtk3 color name -> palette key.
const GTK3_COLORS = [
    ['window_bg_color', 'window_bg'], ['window_fg_color', 'window_fg'],
    ['view_bg_color', 'view_bg'], ['view_fg_color', 'view_fg'],
    ['headerbar_bg_color', 'headerbar_bg'], ['headerbar_fg_color', 'headerbar_fg'],
    ['headerbar_border_color', 'headerbar_border'], ['headerbar_backdrop_color', 'window_bg'],
    ['headerbar_shade_color', 'headerbar_shade'],
    ['sidebar_bg_color', 'sidebar_bg'], ['sidebar_fg_color', 'sidebar_fg'],
    ['card_bg_color', 'card_bg'], ['card_fg_color', 'card_fg'],
    ['popover_bg_color', 'popover_bg'], ['popover_fg_color', 'popover_fg'],
    ['dialog_bg_color', 'dialog_bg'], ['dialog_fg_color', 'dialog_fg'],
    ['accent_color', 'accent'], ['accent_bg_color', 'accent_bg'], ['accent_fg_color', 'accent_fg'],
    ['destructive_color', 'destructive_bg'], ['destructive_bg_color', 'destructive_bg'],
    ['destructive_fg_color', 'destructive_fg'],
    ['success_color', 'success_bg'], ['success_bg_color', 'success_bg'], ['success_fg_color', 'success_fg'],
    ['warning_color', 'warning_bg'], ['warning_bg_color', 'warning_bg'], ['warning_fg_color', 'warning_fg'],
    ['error_color', 'error_bg'], ['error_bg_color', 'error_bg'], ['error_fg_color', 'error_fg'],
    ['borders', 'border'],
];

// GTK3 apps (and Electron/Chromium, which derives light/dark from the GTK3
// window background) read a theme by name and reload it live when the name
// changes, unlike ~/.config/gtk-3.0/gtk.css. So each family variant is a
// small named theme that imports adw-gtk3 and overrides its named colors.
export function gtk3ThemeName(family, isDark) {
    return `paletka-${family.id}-${isDark ? 'dark' : 'light'}`;
}

export function gtk3IndexTheme(name) {
    return `[X-GNOME-Metatheme]
Name=${name}
Type=X-GNOME-Metatheme
Comment=Generated by Paletka
Encoding=UTF-8
GtkTheme=${name}
`;
}

export function gtk3ThemeCss(family, isDark, importPath) {
    const p = resolveVariant(isDark ? family.dark : family.light, isDark);
    const lines = GTK3_COLORS.map(([name, key]) => `@define-color ${name} ${p[key]};`);
    return `${GENERATED_HEADER}
@import url("${GLib.filename_to_uri(importPath, null)}");
/* Theme: ${family.name} (${isDark ? 'dark' : 'light'}) */
${lines.join('\n')}
`;
}

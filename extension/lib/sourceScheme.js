// GtkSourceView 5 style schemes (used by GNOME Text Editor) for a theme family.
// The light and dark scheme point at each other, so Text Editor's "follow"
// style variant switches between them with the desktop.
import {parseHex, toHex, mix, contrastRatio} from './color.js';
import {resolveVariant} from './palette.js';

const variantName = isDark => (isDark ? 'dark' : 'light');

export function sourceSchemeId(family, isDark) {
    return `paletka-${family.id}-${variantName(isDark)}`;
}

const MIN_CONTRAST = 3;

// Pull a color toward the text color until it reaches MIN_CONTRAST on bg.
function readable(color, fg, bg) {
    for (let t = 0; t <= 1; t += 0.1) {
        const c = mix(color, fg, t);
        if (contrastRatio(c, bg) >= MIN_CONTRAST)
            return c;
    }
    return fg;
}

const escape = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

export function sourceSchemeXml(family, isDark) {
    const variant = isDark ? family.dark : family.light;
    const p = resolveVariant(variant, isDark);
    const bg = parseHex(variant.base.background);
    const fg = parseHex(variant.base.foreground);
    const accent = parseHex(variant.base.accent);
    const ansi = variant.terminal.palette.map(parseHex);
    // Normal or bright ANSI color, whichever reads better on the background.
    const hue = i => toHex(readable(
        [ansi[i], ansi[i + 8]].sort((a, b) => contrastRatio(b, bg) - contrastRatio(a, bg))[0], fg, bg));
    const c = {
        bg: toHex(bg),
        fg: toHex(fg),
        comment: toHex(readable(mix(fg, bg, 0.4), fg, bg)),
        lineBg: toHex(mix(bg, fg, 0.06)),
        lineNumbers: toHex(mix(fg, bg, 0.5)),
        selection: toHex(mix(bg, accent, 0.3)),
        accent: p.accent.startsWith('#') ? p.accent : toHex(accent),
        red: hue(1), green: hue(2), yellow: hue(3), blue: hue(4), magenta: hue(5), cyan: hue(6),
    };
    const other = sourceSchemeId(family, !isDark);
    const style = (name, attrs) =>
        `  <style name="${name}" ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`;
    const styles = [
        style('text', {foreground: c.fg, background: c.bg}),
        style('selection', {background: c.selection}),
        style('selection-unfocused', {background: c.lineBg}),
        style('cursor', {foreground: c.fg}),
        style('current-line', {background: c.lineBg}),
        style('current-line-number', {foreground: c.fg, background: c.lineBg}),
        style('line-numbers', {foreground: c.lineNumbers, background: c.bg}),
        style('right-margin', {foreground: c.lineNumbers, background: c.lineBg}),
        style('background-pattern', {background: c.lineBg}),
        style('draw-spaces', {foreground: c.lineNumbers}),
        style('bracket-match', {foreground: c.bg, background: c.accent}),
        style('bracket-mismatch', {foreground: c.bg, background: c.red}),
        style('search-match', {foreground: c.bg, background: c.yellow}),
        style('def:comment', {foreground: c.comment, italic: 'true'}),
        style('def:shebang', {foreground: c.comment, bold: 'true'}),
        style('def:keyword', {foreground: c.magenta, bold: 'true'}),
        style('def:statement', {foreground: c.magenta}),
        style('def:type', {foreground: c.yellow}),
        style('def:string', {foreground: c.green}),
        style('def:constant', {foreground: c.cyan}),
        style('def:special-char', {foreground: c.red}),
        style('def:function', {foreground: c.blue}),
        style('def:preprocessor', {foreground: c.red}),
        style('def:note', {foreground: c.magenta, bold: 'true'}),
        style('def:error', {underline: 'error', 'underline-color': c.red}),
        style('def:heading', {foreground: c.blue, bold: 'true'}),
        style('def:link-text', {foreground: c.cyan}),
        style('def:link-destination', {foreground: c.cyan, underline: 'single'}),
        style('def:inline-code', {foreground: c.green}),
        style('def:emphasis', {italic: 'true'}),
        style('def:strong-emphasis', {bold: 'true'}),
        style('diff:added-line', {foreground: c.green}),
        style('diff:removed-line', {foreground: c.red}),
        style('diff:changed-line', {foreground: c.yellow}),
        style('diff:location', {foreground: c.blue}),
    ];
    return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by Paletka -->
<style-scheme id="${sourceSchemeId(family, isDark)}" name="${escape(family.name)} ${isDark ? 'Dark' : 'Light'}" version="1.0">
  <author>Paletka</author>
  <description>Generated from the ${escape(family.name)} desktop theme</description>
  <metadata>
    <property name="variant">${variantName(isDark)}</property>
    <property name="${isDark ? 'light' : 'dark'}-variant">${other}</property>
  </metadata>
${styles.join('\n')}
</style-scheme>
`;
}

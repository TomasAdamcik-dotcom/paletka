// Optional: Google Chrome's window follows the GTK theme only when Chrome runs
// with GTK 3, so a user copy of its launcher adds --gtk-version=3.
export const CHROME_DESKTOP = 'google-chrome.desktop';
const HEADER = '# Generated by Paletka — do not edit.';

export function chromeDesktopOverride(systemText) {
    const lines = systemText.split('\n').map(line => {
        const m = /^Exec=(\S+)(.*)$/.exec(line);
        return m ? `Exec=${m[1]} --gtk-version=3${m[2]}` : line;
    });
    return `${HEADER}\n${lines.join('\n')}`;
}

const userPath = paths => `${paths.applicationsDir}/${CHROME_DESKTOP}`;

// 'ok' | 'conflict' (the user has an own launcher) | 'missing' (no Chrome).
export function enableChromeWindow(fs, paths) {
    const system = paths.systemApplicationsDirs
        .map(dir => fs.readText(`${dir}/${CHROME_DESKTOP}`))
        .find(text => text !== null);
    if (system === undefined) {
        // Chrome was uninstalled: a launcher for it would not start anything.
        disableChromeWindow(fs, paths);
        return 'missing';
    }
    const current = fs.readText(userPath(paths));
    if (current !== null && !current.startsWith(HEADER))
        return 'conflict';
    fs.writeText(userPath(paths), chromeDesktopOverride(system));
    return 'ok';
}

export function disableChromeWindow(fs, paths) {
    if (fs.readText(userPath(paths))?.startsWith(HEADER))
        fs.remove(userPath(paths));
}

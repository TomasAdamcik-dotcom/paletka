// Terminal color outputs: Ptyxis palette files and GNOME Terminal profile keys.

export function ptyxisPaletteId(family) {
    return `paletka-${family.id}`;
}

function ptyxisSection(name, t) {
    const lines = [
        `[${name}]`,
        `Foreground=${t.foreground}`,
        `Background=${t.background}`,
        `TitlebarForeground=${t.foreground}`,
        `Cursor=${t.cursor}`,
        ...t.palette.map((c, i) => `Color${i}=${c}`),
    ];
    return lines.join('\n');
}

export function ptyxisPalette(family) {
    return `# Generated by Paletka — do not edit.
[Palette]
Name=${family.name} (Paletka)

${ptyxisSection('Light', family.light.terminal)}

${ptyxisSection('Dark', family.dark.terminal)}
`;
}

export const GNOME_TERMINAL_KEYS = [
    'use-theme-colors', 'foreground-color', 'background-color', 'palette',
    'bold-color-same-as-fg', 'cursor-colors-set', 'cursor-background-color', 'cursor-foreground-color',
];

export function gnomeTerminalValues(t) {
    return {
        'use-theme-colors': false,
        'foreground-color': t.foreground,
        'background-color': t.background,
        'palette': [...t.palette],
        'bold-color-same-as-fg': true,
        'cursor-colors-set': true,
        'cursor-background-color': t.cursor,
        'cursor-foreground-color': t.background,
    };
}

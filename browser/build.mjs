// Builds dist/chrome and dist/firefox (and their zips) from src/.
// Content scripts cannot be modules, so their modules are joined into one
// file, each in its own scope, with the import and export keywords removed.
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.dirname(new URL(import.meta.url).pathname);
const src = path.join(root, 'src');
const CONTENT = ['recolor/colors.js', 'recolor/mapping.js', 'recolor/recolorer.js', 'content/main.js'];
const COPY = ['background.js', 'connection.js', 'firefoxTheme.js'];
const DIRS = ['popup', 'icons'];

// Each module keeps its own scope; only its exports reach the next ones.
function contentBundle() {
    const parts = CONTENT.filter(f => fs.existsSync(path.join(src, f))).map(f => {
        const source = fs.readFileSync(path.join(src, f), 'utf8');
        const names = [...source.matchAll(/^export (?:const|function|class|let) (\w+)/gm)].map(m => m[1]);
        const code = source
            .replace(/^import [^;]+;\n/gm, '')
            .replace(/^export (?=(const|function|class|let) )/gm, '');
        if (!names.length)
            return `// ${f}\n{\n${code}}\n`;
        return `// ${f}\nconst {${names.join(', ')}} = (() => {\n${code}\nreturn {${names.join(', ')}};\n})();\n`;
    });
    return `// Generated by build.mjs from src/; do not edit.\n(() => {\n${parts.join('\n')}\n})();\n`;
}

export function build(target) {
    const out = path.join(root, 'dist', target);
    fs.rmSync(out, {recursive: true, force: true});
    fs.mkdirSync(out, {recursive: true});
    fs.copyFileSync(path.join(root, `manifest.${target}.json`), path.join(out, 'manifest.json'));
    for (const f of COPY)
        fs.copyFileSync(path.join(src, f), path.join(out, f));
    for (const d of DIRS) {
        if (fs.existsSync(path.join(src, d)))
            fs.cpSync(path.join(src, d), path.join(out, d), {recursive: true});
    }
    fs.writeFileSync(path.join(out, 'content.js'), contentBundle());
    const zip = path.join(root, 'dist', `paletka-${target}.zip`);
    fs.rmSync(zip, {force: true});
    execFileSync('zip', ['-qr', zip, '.'], {cwd: out});
    return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    for (const target of ['chrome', 'firefox'])
        console.log(build(target));
}

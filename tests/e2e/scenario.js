// PID of Nautilus in the nested session (the real session may run one too).
function nautilusPids() {
    try {
        const [pid] = call('org.freedesktop.DBus', '/org/freedesktop/DBus', 'org.freedesktop.DBus',
            'GetConnectionUnixProcessID', new GLib.Variant('(s)', ['org.gnome.Nautilus']), '(u)').deepUnpack();
        return [String(pid)];
    } catch {
        return [];
    }
}

function filesWindows() {
    try {
        const [v] = call('org.gnome.Nautilus', '/org/freedesktop/FileManager1', 'org.freedesktop.DBus.Properties',
            'Get', new GLib.Variant('(ss)', ['org.freedesktop.FileManager1', 'OpenWindowsWithLocations']),
            '(v)').recursiveUnpack();
        return Object.values(v);
    } catch {
        return [];
    }
}


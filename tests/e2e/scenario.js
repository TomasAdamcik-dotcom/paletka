step('7d. Files is not restarted while it copies, but right after', () => {
    const copied = () => {
        const [, out] = GLib.spawn_command_line_sync(`sh -c "ls ${HOME}/Documents/copy-src 2>/dev/null | wc -l"`);
        return new TextDecoder().decode(out).trim();
    };
    const before = nautilusPids();
    // Fire and forget: the call may only return when the copy is done.
    bus.call('org.gnome.Nautilus', '/org/gnome/Nautilus/FileOperations2', 'org.gnome.Nautilus.FileOperations2',
        'CopyURIs', new GLib.Variant('(assa{sv})', [[`file://${HOME}/copy-src`], `file://${HOME}/Documents`, {}]),
        null, Gio.DBusCallFlags.NONE, -1, null, null);
    sleep(500);
    selectFamily('Nord');
    sleep(6000);
    print(`     files copied 6 s after the switch: ${copied()}`);
    assert(nautilusPids().join() === before.join(), 'Files was not restarted during the copy');
    waitFor('copy finished', () => copied() === '150000', 120000);
    waitFor('Files restarted after the copy', () => {
        const now = nautilusPids();
        return now.length > 0 && !now.some(p => before.includes(p));
    }, 60000);
    waitFor('window reopened', () => filesWindows().some(w => w[0]?.endsWith('/Documents')), 15000);
    ext.set_boolean('restart-background-services', false);
});


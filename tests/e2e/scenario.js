let failures = 0;

function step(name, fn) {
    try {
        fn();
        print(`ok   ${name}`);
    } catch (e) {
        failures++;
        print(`FAIL ${name}\n     ${e.message}`);
    }
}

function assert(cond, msg) {
    if (!cond)
        throw new Error(msg);
}

function sleep(ms) {
    const loop = GLib.MainLoop.new(null, false);
    GLib.timeout_add(GLib.PRIORITY_DEFAULT, ms, () => {
        loop.quit();
        return GLib.SOURCE_REMOVE;
    });
    loop.run();
}

function waitFor(desc, fn, timeoutMs = 6000) {
    const end = Date.now() + timeoutMs;
    let last;
    while (Date.now() < end) {
        try {
            last = fn();
            if (last)
                return last;
        } catch (e) {
            last = e.message;
        }
        sleep(200);
    }
    throw new Error(`timed out waiting for ${desc} (last: ${JSON.stringify(last)})`);
}

function call(dest, path, ifaceName, method, params, replyType) {
    return bus.call_sync(dest, path, ifaceName, method, params,
        replyType ? new GLib.VariantType(replyType) : null, Gio.DBusCallFlags.NONE, 10000, null);
}

function evalShell(code) {
    const [ok, json] = call('org.gnome.Shell', '/org/gnome/Shell', 'org.gnome.Shell', 'Eval',
        new GLib.Variant('(s)', [code]), '(bs)').deepUnpack();
    if (!ok)
        throw new Error(`Eval failed: ${json}`);
    return json ? JSON.parse(json) : undefined;
}

function screenshot(name) {
    sleep(700);
    const path = `${OUT}/${name}.png`;
    call('org.gnome.Shell.Screenshot', '/org/gnome/Shell/Screenshot', 'org.gnome.Shell.Screenshot',
        'Screenshot', new GLib.Variant('(bbs)', [false, false, path]), '(bs)');
    print(`     screenshot ${path}`);
}

function read(path) {
    try {
        return new TextDecoder().decode(GLib.file_get_contents(path)[1]);
    } catch {
        return null;
    }
}

function write(path, text) {
    GLib.mkdir_with_parents(GLib.path_get_dirname(path), 0o755);
    GLib.file_set_contents(path, text);
}

function probe(args = ['print']) {
    const proc = Gio.Subprocess.new(['python3', `${ROOT}/tests/e2e/probe-gtk4.py`, ...args],
        Gio.SubprocessFlags.STDOUT_PIPE | Gio.SubprocessFlags.STDERR_SILENCE);
    return proc;
}

function probeColor() {
    const proc = probe();
    const [, out] = proc.communicate_utf8(null, null);
    return out.trim();
}

// Shell-side helpers evaluated with Main in scope.
// Each theme row ends with its Dark and Light buttons, named "<theme> Dark|Light".
const FIND_TOGGLE = `
    const buttonsOf = i => i.get_children().at(-1).get_children();
    const nameOf = i => buttonsOf(i)[0].accessible_name.replace(/ Dark$/, '');
    const qs = Main.panel.statusArea.quickSettings;
    const kids = qs.menu._grid.get_children();
    const toggles = kids.filter(k => k.constructor.name.includes('ThemeToggle'));
    const toggle = toggles[0];
`;

function toggleInfo() {
    return evalShell(`(() => {${FIND_TOGGLE}
        const dark = qs._darkMode.quickSettingsItems[0];
        return {count: toggles.length, index: kids.indexOf(toggle), darkIndex: kids.indexOf(dark),
            subtitle: toggle?.subtitle ?? null, checked: toggle?.checked ?? null,
            items: toggle ? toggle._section._getMenuItems().map(nameOf) : []};
    })()`);
}

function ourStylesheets() {
    return evalShell(`(async () => {
        const St = (await import('gi://St')).default;
        return St.ThemeContext.get_for_stage(global.stage).get_theme().get_custom_stylesheets()
            .map(f => f.get_path()).filter(p => p.includes('/paletka/shell-'));
    })()`);
}

// Clicks the Dark or Light button of a theme row (default: the current scheme).
function selectFamily(name, dark = iface.get_string('color-scheme') === 'prefer-dark') {
    evalShell(`(() => {${FIND_TOGGLE}
        const item = toggle._section._getMenuItems().find(i => nameOf(i) === ${JSON.stringify(name)});
        buttonsOf(item)[${dark} ? 0 : 1].emit('clicked', 1);
        return true;
    })()`);
}

function activeButtons() {
    return evalShell(`(() => {${FIND_TOGGLE}
        return toggle._section._getMenuItems().flatMap(i => buttonsOf(i)
            .filter(b => b.has_style_class_name('paletka-variant-active')).map(b => nameOf(i) + ' ' + b.label));
    })()`);
}

function openMenus({quick = true, themeMenu = false} = {}) {
    evalShell(`(() => {${FIND_TOGGLE}
        Main.messageTray.getSources().forEach(s => s.destroy());
        if (${quick}) qs.menu.open(false); else qs.menu.close(false);
        if (${themeMenu}) toggle.menu.open(false); else toggle.menu.close(false);
        return true;
    })()`);
}

function extensionInfo() {
    const [info] = call('org.gnome.Shell', '/org/gnome/Shell', 'org.gnome.Shell.Extensions',
        'GetExtensionInfo', new GLib.Variant('(s)', [UUID]), '(a{sv})').recursiveUnpack();
    return info;
}


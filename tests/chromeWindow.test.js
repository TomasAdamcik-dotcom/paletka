import {test, assertEq} from './harness.js';
import {setup} from './applierSetup.js';
import {
    CHROME_DESKTOP, chromeDesktopOverride, enableChromeWindow, disableChromeWindow,
} from '../extension/lib/chromeWindow.js';

const SYSTEM = `[Desktop Entry]
Version=1.0
Name=Google Chrome
Exec=/usr/bin/google-chrome-stable %U
Actions=new-window;new-private-window;

[Desktop Action new-window]
Name=New Window
Exec=/usr/bin/google-chrome-stable

[Desktop Action new-private-window]
Name=New Incognito Window
Exec=/usr/bin/google-chrome-stable --incognito
`;

test('chromeWindow: every Exec line gets --gtk-version=3 after the binary', () => {
    const text = chromeDesktopOverride(SYSTEM);
    assertEq(text.split('\n')[0], '# Generated by Paletka — do not edit.');
    assertEq(text.split('\n').filter(l => l.startsWith('Exec=')), [
        'Exec=/usr/bin/google-chrome-stable --gtk-version=3 %U',
        'Exec=/usr/bin/google-chrome-stable --gtk-version=3',
        'Exec=/usr/bin/google-chrome-stable --gtk-version=3 --incognito',
    ]);
    assertEq(text.split('\n').filter(l => !l.startsWith('Exec=') && !l.startsWith('#')),
        SYSTEM.split('\n').filter(l => !l.startsWith('Exec=')));
});

function env() {
    const {fs, paths} = setup();
    paths.systemApplicationsDirs = [`${paths.home}/system-apps`];
    fs.writeText(`${paths.home}/system-apps/${CHROME_DESKTOP}`, SYSTEM);
    return {fs, paths, user: `${paths.applicationsDir}/${CHROME_DESKTOP}`};
}

test('chromeWindow: enabling writes the user override, disabling removes it', () => {
    const {fs, paths, user} = env();
    assertEq(enableChromeWindow(fs, paths), 'ok');
    assertEq(fs.readText(user), chromeDesktopOverride(SYSTEM));
    disableChromeWindow(fs, paths);
    assertEq(fs.exists(user), false);
});

test('chromeWindow: a launcher of the user is left alone and reported', () => {
    const {fs, paths, user} = env();
    fs.writeText(user, '[Desktop Entry]\nExec=my-chrome\n');
    assertEq(enableChromeWindow(fs, paths), 'conflict');
    disableChromeWindow(fs, paths);
    assertEq(fs.readText(user), '[Desktop Entry]\nExec=my-chrome\n');
});

test('chromeWindow: without Chrome there is nothing to do', () => {
    const {fs, paths} = setup();
    paths.systemApplicationsDirs = [`${paths.home}/none`];
    assertEq(enableChromeWindow(fs, paths), 'missing');
});

test('chromeWindow: turning Paletka off removes the override', () => {
    const {applier, fs, paths, user} = (() => {
        const s = setup();
        s.paths.systemApplicationsDirs = [`${s.paths.home}/system-apps`];
        s.fs.writeText(`${s.paths.home}/system-apps/${CHROME_DESKTOP}`, SYSTEM);
        return {...s, user: `${s.paths.applicationsDir}/${CHROME_DESKTOP}`};
    })();
    enableChromeWindow(fs, paths);
    applier.removeLeftovers();
    assertEq(fs.exists(user), false);
});

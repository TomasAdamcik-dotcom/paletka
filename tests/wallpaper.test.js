import {test, assert, assertEq} from './harness.js';
import {wallpaperSvg} from '../extension/lib/wallpaper.js';

test('wallpaper: gradient svg', () => {
    const svg = wallpaperSvg({type: 'gradient', from: '#002b36', to: '#073642'});
    assert(svg.startsWith('<?xml'));
    assert(svg.includes('Generated by Paletka'));
    assert(svg.includes('linearGradient'));
    assert(svg.includes('#002b36') && svg.includes('#073642'));
});

test('wallpaper: solid svg', () => {
    assert(wallpaperSvg({type: 'solid', color: '#123456'}).includes('fill="#123456"'));
});

test('wallpaper: none and file produce no svg', () => {
    assertEq(wallpaperSvg({type: 'none'}), null);
    assertEq(wallpaperSvg({type: 'file', path: '/x.png'}), null);
});
